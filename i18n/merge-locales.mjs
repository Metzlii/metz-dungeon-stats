// Fold the translators' files into the userscript's locale block, checked:
//   - every key must be one of en-keys.json (a stray key is reported and dropped);
//   - every {placeholder} of the key must be in the translation, and no other (else the string stays English);
//   - empty or identical-to-English translations are left out (English is the fallback anyway).
// Writes the block between "// <locales>" and "// </locales>" (created before the Start section the first time).
//   node merge-locales.mjs [--dry]
import fs from "node:fs";
const DIR = new URL("./", import.meta.url);
const SRC = new URL("../metz-dungeon-stats.user.js", import.meta.url);
const LANGS = ["es", "fr", "ja", "ko", "pt", "ru", "zh", "zh-Hant"];
const keys = JSON.parse(fs.readFileSync(new URL("en-keys.json", DIR), "utf8"));
const keySet = new Set(keys);
const ph = s => (s.match(/\{[a-z0-9_]+\}/gi) || []).sort().join(",");
const out = {}, report = [];
for (const lang of LANGS) {
    const f = new URL(`${lang}.json`, DIR);
    if (!fs.existsSync(f)) { report.push(`${lang}: no file`); continue; }
    const tr = JSON.parse(fs.readFileSync(f, "utf8"));
    const kept = {}; let bad = 0, stray = 0, same = 0;
    for (const [k, v] of Object.entries(tr)) {
        if (!keySet.has(k)) { stray++; continue; }
        if (typeof v !== "string" || !v.trim()) continue;
        if (v === k && /[A-Za-z]{3}/.test(k)) { same++; continue; }
        if (ph(k) !== ph(v)) { bad++; report.push(`${lang} placeholder mismatch: ${JSON.stringify(k)} -> ${JSON.stringify(v)}`); continue; }
        kept[k] = v;
    }
    const missing = keys.filter(k => !(k in tr));
    report.push(`${lang}: ${Object.keys(kept).length}/${keys.length} kept, ${missing.length} missing, ${bad} placeholder mismatches, ${stray} stray, ${same} left as English`);
    out[lang] = Object.fromEntries(Object.keys(kept).sort().map(k => [k, kept[k]]));
}
console.log(report.join("\n"));
if (process.argv.includes("--dry")) process.exit(0);
let src = fs.readFileSync(SRC, "utf8");
const block = `    // <locales>
    // Our words in the game's languages, keyed by the English (generated by i18n/merge-locales.mjs
    // from the translators' files, placeholders checked). A string missing here shows in English.
    Object.assign(I18N, ${JSON.stringify(out, null, 1).replace(/\n/g, "\n    ")});
    // </locales>
`;
if (src.includes("    // <locales>")) src = src.replace(/    \/\/ <locales>[\s\S]*?    \/\/ <\/locales>\n/, block);
else {
    const anchor = "    // ---------------------------------------------------------------------------------------------------------------\n    // Start\n";
    if (!src.includes(anchor)) throw new Error("Start section not found");
    src = src.replace(anchor, block + "\n" + anchor);
}
const tmp = new URL("../metz-dungeon-stats.user.js.tmp", import.meta.url); fs.writeFileSync(tmp, src); fs.renameSync(tmp, SRC);
console.log("written");
